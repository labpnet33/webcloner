#!/usr/bin/env node
"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const os=require("node:os");
const path=require("node:path");
const {spawnSync}=require("node:child_process");

test("resumes in batches and recovers older captures without overwriting data",t=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),"webcloner-resume-"));
  t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
  const modules=path.join(temp,"stubs");
  fs.mkdirSync(path.join(modules,"playwright"),{recursive:true});
  fs.mkdirSync(path.join(modules,"robots-parser"),{recursive:true});
  const links=Array.from({length:7},(_,i)=>"https://example.test/page"+(i+1));
  const html="<html><head><title>Test site</title></head><body>"+
    links.map(u=>'<a href="'+u+'">Page</a>').join("")+"</body></html>";
  const mock=[
    "module.exports={chromium:{launch:async()=>({",
    "newContext:async()=>({route:async()=>{},",
    "newPage:async()=>{let current='';return{",
    "on:()=>{},goto:async u=>{current=u;return{status:()=>200,ok:()=>true}},",
    "url:()=>current,waitForLoadState:async()=>{},evaluate:async()=>{},",
    "waitForTimeout:async()=>{},title:async()=>current,",
    "locator:()=>({evaluateAll:async()=>"+JSON.stringify(links)+"}),",
    "content:async()=>"+JSON.stringify(html)+",",
    "close:async()=>{},screenshot:async()=>{}",
    "}},close:async()=>{}}),close:async()=>{}})}}"
  ].join("\n");
  fs.writeFileSync(path.join(modules,"playwright","index.js"),mock);
  fs.writeFileSync(path.join(modules,"robots-parser","index.js"),
    "module.exports=()=>({isAllowed:()=>true});\n");
  const preload=path.join(temp,"preload.cjs");
  fs.writeFileSync(preload,
    "global.fetch=async u=>new Response("+JSON.stringify(
      "<urlset>"+links.map(u=>"<loc>"+u+"</loc>").join("")+"</urlset>"
    )+",{status:200,headers:{'content-type':'application/xml'}});\n");
  const capture=path.join(temp,"capture");
  const runner=path.join(__dirname,"..","capture-site.cjs");
  const base=["https://example.test/","--out",capture,"--max-pages","2",
    "--max-depth","8","--max-assets","20","--max-total-mb","10",
    "--no-deep-assets","--no-screenshots"];
  const run=(args)=>spawnSync(process.execPath,[runner,...args],{
    encoding:"utf8",timeout:30000,
    env:{...process.env,NODE_PATH:modules,NODE_OPTIONS:"--require="+preload}
  });
  const readPages=()=>JSON.parse(fs.readFileSync(path.join(capture,"pages.json"),"utf8"));
  let result=run(base);
  assert.equal(result.status,0,"first run: "+result.stderr+"\n"+result.stdout);
  assert.equal(readPages().length,2);
  const originalUrls=new Set(readPages().map(p=>p.url));
  assert.equal(originalUrls.size,2);
  assert.ok(fs.existsSync(path.join(capture,"checkpoint.json")));

  result=run([...base,"--resume"]);
  assert.equal(result.status,0,"checkpoint resume: "+result.stderr+"\n"+result.stdout);
  assert.equal(readPages().length,4);
  assert.equal(new Set(readPages().map(p=>p.url)).size,4);
  assert.ok(readPages().some(p=>!originalUrls.has(p.url)));
  assert.ok(JSON.parse(fs.readFileSync(path.join(capture,"checkpoint.json"),"utf8")).queue.length>0);

  // Simulate a capture generated by an older Webcloner without checkpoint.json.
  fs.unlinkSync(path.join(capture,"checkpoint.json"));
  result=run([...base,"--resume","--no-sitemap"]);
  assert.equal(result.status,0,"legacy resume: "+result.stderr+"\n"+result.stdout);
  assert.equal(readPages().length,6);
  assert.equal(new Set(readPages().map(p=>p.url)).size,6);

  const originalManifest=fs.readFileSync(path.join(capture,"manifest.json"),"utf8");
  result=run([...base,"--max-pages","1"]);
  assert.notEqual(result.status,0,"non-resume on existing directory must fail");
  assert.equal(fs.readFileSync(path.join(capture,"manifest.json"),"utf8"),originalManifest);

  result=run(["https://different.test/","--out",capture,"--resume","--max-pages","1",
    "--no-sitemap","--no-deep-assets","--no-screenshots"]);
  assert.notEqual(result.status,0,"resume of a different site must fail");
  assert.equal(fs.readFileSync(path.join(capture,"manifest.json"),"utf8"),originalManifest);
});
